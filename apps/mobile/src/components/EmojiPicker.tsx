export default function EmojiPicker({ visible, onClose, onSelect }: { visible: boolean; onClose: () => void; onSelect: (emoji: string) => void }) {
  const [query, setQuery] = useState('');
  const [activeTab, setActiveTab] = useState(0);

  const filtered = query.trim()
    ? EMOJI_DATA.flatMap(c => c.emojis).filter(e => e.includes(query))
    : EMOJI_DATA[activeTab]?.emojis ?? [];

  return (
    <Modal visible={visible} transparent animationType="fade" onRequestClose={onClose}>
      <Pressable style={styles.bg} onPress={onClose}>
        <View style={styles.card} onStartShouldSetResponder={() => true}>
          <TextInput style={styles.search} placeholder="Search emoji..." placeholderTextColor={colors.textMuted} value={query} onChangeText={setQuery} />
          {!query && (
            <View style={styles.tabs}>
              {EMOJI_DATA.map((cat, i) => (
                <TouchableOpacity key={cat.name} onPress={() => setActiveTab(i)} style={[styles.tab, activeTab === i && styles.tabActive]}>
                  <Text style={styles.tabText}>{cat.emojis[0]}</Text>
                </TouchableOpacity>
              ))}
            </View>
          )}
          <FlatList
            data={filtered}
            keyExtractor={(e, i) => `${e}-${i}`}
            numColumns={8}
            style={{ maxHeight: 240 }}
            renderItem={({ item }) => (
              <TouchableOpacity style={styles.emojiBtn} onPress={() => { onSelect(item); onClose(); }}>
                <Text style={styles.emoji}>{item}</Text>
              </TouchableOpacity>
            )}
            ListEmptyComponent={<Text style={styles.empty}>No emojis found.</Text>}
          />
        </View>
      </Pressable>
    </Modal>
  );
}

const styles = StyleSheet.create({
  bg: { flex: 1, backgroundColor: 'rgba(0,0,0,0.75)', justifyContent: 'center', alignItems: 'center', padding: 24 },
  card: { backgroundColor: colors.card, borderRadius: 16, borderWidth: 1, borderColor: colors.border, width: '100%', maxWidth: 400, padding: 12 },
  search: { backgroundColor: colors.bg4, color: colors.text, padding: 10, borderRadius: 8, marginBottom: 8 },
  tabs: { flexDirection: 'row', justifyContent: 'space-around', marginBottom: 8, paddingVertical: 4, borderBottomWidth: 1, borderBottomColor: colors.border },
  tab: { padding: 4, opacity: 0.5 },
  tabActive: { opacity: 1 },
  tabText: { fontSize: 20 },
  emojiBtn: { width: '12.5%', aspectRatio: 1, alignItems: 'center', justifyContent: 'center' },
  emoji: { fontSize: 24 },
  empty: { color: colors.textDim, textAlign: 'center', padding: 20 },
});